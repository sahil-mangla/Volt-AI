def create_nasa_synthetic_data():
    """
    Create realistic NASA battery data matching the actual dataset structure
    """
    np.random.seed(42)

    # NASA battery IDs from the actual dataset
    battery_ids = ['B0005', 'B0006', 'B0007', 'B0018']

    all_cycles = []

    for battery_id in battery_ids:
        # NASA dataset characteristics
        if battery_id == 'B0005':
            initial_capacity = 1.856
            degradation_rate = 0.0038
            max_cycles = 168
            ir_base = 0.05
        elif battery_id == 'B0006':
            initial_capacity = 1.869
            degradation_rate = 0.0032
            max_cycles = 168
            ir_base = 0.048
        elif battery_id == 'B0007':
            initial_capacity = 1.885
            degradation_rate = 0.0041
            max_cycles = 168
            ir_base = 0.052
        else:  # B0018
            initial_capacity = 1.879
            degradation_rate = 0.0035
            max_cycles = 132
            ir_base = 0.049

        for cycle in range(1, max_cycles + 1):
            # Number of measurements in this cycle
            n_samples = np.random.randint(100, 300)

            # Create time points (0 to 100 minutes for a cycle)
            time = np.linspace(0, 100, n_samples)

            # Capacity for this cycle (degrading over cycles)
            if cycle < 20:
                # Initial stabilization phase
                base_capacity = initial_capacity * (1 - 0.0005 * cycle)
            else:
                # Exponential degradation
                base_capacity = initial_capacity * np.exp(-degradation_rate * (cycle - 20))

            # Add measurement noise
            capacity = base_capacity + np.random.normal(0, 0.015, n_samples)

            # Voltage curve (typical charge/discharge profile)
            # Charge phase (0-30 minutes): voltage rises
            # Discharge phase (30-100 minutes): voltage drops
            voltage_charge = 3.6 + 0.4 * (time[time <= 30] / 30)
            voltage_discharge = 4.0 - 0.5 * ((time[time > 30] - 30) / 70)

            voltage = np.concatenate([voltage_charge, voltage_discharge])
            # Add noise and cycle degradation
            voltage += np.random.normal(0, 0.03, n_samples) - 0.001 * cycle

            # Current profile
            current_charge = 1.5 + 0.3 * np.sin(2 * np.pi * time[time <= 30] / 15)
            current_discharge = -1.8 + 0.2 * np.sin(2 * np.pi * (time[time > 30] - 30) / 35)
            current = np.concatenate([current_charge, current_discharge])

            # Temperature profile
            temperature = 25 + 8 * np.sin(np.pi * time / 100) + 0.008 * cycle
            temperature += np.random.normal(0, 1.5, n_samples)

            # Internal resistance (increases with cycles)
            internal_resistance = ir_base + 0.00035 * cycle + np.random.normal(0, 0.002, n_samples)

            # Additional NASA metrics
            power = voltage * np.abs(current)
            energy = np.cumsum(power) * (100 / n_samples) / 3600  # Wh

            # Create cycle dataframe with NASA-like column names
            cycle_df = pd.DataFrame({
                'Time': time,
                'Voltage_measured': voltage,
                'Current_measured': current,
                'Temperature_measured': temperature,
                'Capacity': capacity,
                'Internal_resistance': internal_resistance,
                'Power': power,
                'Energy': energy,
                'Voltage_load': voltage - internal_resistance * current,
                'Current_load': current,
                'battery_id': battery_id,
                'cycle': cycle,
                'filename': f'{battery_id}_cycle{cycle}.csv'
            })

            all_cycles.append(cycle_df)

    # Combine all cycles
    df_combined = pd.concat(all_cycles, ignore_index=True)

    print(f"✅ Created realistic NASA-style dataset")
