        if len(critical_cycles) > 0:
            eol_cycle = critical_cycles['cycle'].iloc[0]
            cycle_df['rul'] = eol_cycle - cycle_df['cycle']
        else:
            # Method 2: Linear extrapolation based on recent trend
            if len(cycle_df) > 30:
                recent_health = cycle_df['health_score'].iloc[-30:].values
                cycles_idx = np.arange(len(recent_health))

                if len(np.unique(recent_health)) > 1:
                    # Fit linear regression
                    slope, intercept = np.polyfit(cycles_idx, recent_health, 1)

                    if slope < 0:  # Only if degrading
                        cycles_to_eol = (70 - intercept) / abs(slope)
                        cycle_df['rul'] = cycles_to_eol - (len(cycle_df) - 30) + cycles_idx
                    else:
                        # If not degrading, set conservative estimate
                        cycle_df['rul'] = 200 - cycle_df['cycle']
                else:
                    cycle_df['rul'] = 150 - cycle_df['cycle']
            else:
                cycle_df['rul'] = 100 - cycle_df['cycle']

